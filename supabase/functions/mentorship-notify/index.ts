// Sends Aditya one digest email for mentorship payments, call requests, mentee
// chat messages and student feedback. Scheduled by pg_cron every few minutes;
// safe to call by hand. It only ever reports counts, never student data.

type NotificationKind = "payment" | "call" | "chat" | "feedback";

type QueueItem = {
  kind: NotificationKind;
  item_id: string;
  student: string | null;
  contact: string | null;
  headline: string | null;
  detail: string | null;
  occurred_at: string | null;
};

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, apikey, content-type, x-client-info",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
};

const MENTOR_EMAIL = "adityabakshi1011@gmail.com";

function respond(body: unknown, status = 200) {
  return new Response(JSON.stringify(body), { status, headers: { ...corsHeaders, "Content-Type": "application/json" } });
}

function escapeHtml(value: string) {
  return value.replace(/[&<>"']/g, (character) =>
    ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[character]!);
}

function inIst(value: string | null) {
  if (!value) return "";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "";
  return new Intl.DateTimeFormat("en-IN", {
    timeZone: "Asia/Kolkata", dateStyle: "medium", timeStyle: "short",
  }).format(date) + " IST";
}

function itemsByKind(items: QueueItem[]) {
  const groups = new Map<NotificationKind, QueueItem[]>();
  for (const item of items) {
    const bucket = groups.get(item.kind) ?? [];
    bucket.push(item);
    groups.set(item.kind, bucket);
  }
  return groups;
}

const kindLabels: Record<NotificationKind, string> = {
  payment: "Payment claim",
  call: "Call request",
  chat: "Mentee message",
  feedback: "Student feedback",
};

// A new queue kind can reach this function before its label is deployed, and
// losing the whole batch is far worse than a generic heading.
function labelFor(kind: NotificationKind) {
  return kindLabels[kind] ?? "CodexSheet alert";
}

function subjectLine(groups: Map<NotificationKind, QueueItem[]>) {
  const parts = [...groups].map(([kind, list]) => `${list.length} ${labelFor(kind)}${list.length > 1 ? "s" : ""}`);
  return `CodexSheet alerts · ${parts.join(" · ")}`;
}

function renderHtml(groups: Map<NotificationKind, QueueItem[]>) {
  const sections = [...groups].map(([kind, list]) => {
    const rows = list.map((item) => `
      <tr>
        <td style="padding:10px 12px;border-bottom:1px solid #eef1f6;font-size:14px;">
          <strong>${escapeHtml(item.student ?? "Unknown")}</strong><br/>
          <span style="color:#4b5563;">${escapeHtml(item.headline ?? "")}</span><br/>
          ${item.detail ? `<span style="color:#4b5563;">${escapeHtml(item.detail)}</span><br/>` : ""}
          <span style="color:#9aa3b2;font-size:12px;">${escapeHtml(item.contact ?? "")}${item.contact ? " · " : ""}${inIst(item.occurred_at)}</span>
        </td>
      </tr>`).join("");
    return `
      <h2 style="margin:22px 0 8px;font-size:15px;letter-spacing:.04em;text-transform:uppercase;color:#1f2a44;">${labelFor(kind)}</h2>
      <table role="presentation" cellpadding="0" cellspacing="0" style="width:100%;border-collapse:collapse;border:1px solid #e3e8f0;border-radius:10px;overflow:hidden;">${rows}</table>`;
  }).join("");
  return `<div style="font-family:ui-sans-serif,system-ui,-apple-system,Segoe UI,Roboto,sans-serif;color:#111827;">
    <p style="margin:0 0 6px;font-size:14px;color:#4b5563;">New activity in your CodexSheet workspace.</p>
    ${sections}
    <p style="margin:22px 0 0;font-size:12px;color:#9aa3b2;">Open the Paytm app to confirm payments before the first session. This mail is generated by the CodexSheet notification job.</p>
  </div>`;
}

function renderText(groups: Map<NotificationKind, QueueItem[]>) {
  const lines: string[] = ["New activity in your CodexSheet workspace.", ""];
  for (const [kind, list] of groups) {
    lines.push(labelFor(kind).toUpperCase());
    for (const item of list) {
      lines.push(`- ${item.student ?? "Unknown"}: ${item.headline ?? ""}`);
      if (item.detail) lines.push(`  ${item.detail}`);
      const trail = [item.contact, inIst(item.occurred_at)].filter(Boolean).join(" · ");
      if (trail) lines.push(`  ${trail}`);
    }
    lines.push("");
  }
  lines.push("Confirm payments in the Paytm app before the first session.");
  return lines.join("\n");
}

async function requeue(items: QueueItem[]) {
  const supabaseUrl = Deno.env.get("SUPABASE_URL")?.trim();
  const serviceRoleKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")?.trim();
  if (!supabaseUrl || !serviceRoleKey) return;
  for (const [kind, list] of itemsByKind(items)) {
    try {
      await fetch(`${supabaseUrl}/rest/v1/rpc/mentorship_notification_retry`, {
        method: "POST",
        headers: { apikey: serviceRoleKey, Authorization: `Bearer ${serviceRoleKey}`, "Content-Type": "application/json" },
        body: JSON.stringify({ p_kind: kind, p_item_ids: list.map((item) => item.item_id) }),
        signal: AbortSignal.timeout(8000),
      });
    } catch {
      // The next scheduler run picks the rows up again on its own.
    }
  }
}

Deno.serve(async (request: Request) => {
  if (request.method === "OPTIONS") return new Response("ok", { headers: corsHeaders });
  if (request.method !== "POST") return respond({ error: "Use POST to run the notifier." }, 405);

  const supabaseUrl = Deno.env.get("SUPABASE_URL")?.trim();
  const serviceRoleKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")?.trim();
  const resendApiKey = Deno.env.get("RESEND_API_KEY")?.trim();
  const from = Deno.env.get("EMAIL_FROM")?.trim() || "CodexSheet Alerts <onboarding@resend.dev>";
  const to = Deno.env.get("NOTIFY_TO")?.trim() || MENTOR_EMAIL;

  if (!supabaseUrl || !serviceRoleKey) return respond({ error: "Supabase credentials are missing on the server." }, 503);
  if (!resendApiKey) return respond({ error: "Set RESEND_API_KEY to deliver notification mail." }, 503);

  let items: QueueItem[];
  try {
    const queueResponse = await fetch(`${supabaseUrl}/rest/v1/rpc/mentorship_pending_notifications`, {
      method: "POST",
      headers: { apikey: serviceRoleKey, Authorization: `Bearer ${serviceRoleKey}`, "Content-Type": "application/json" },
      body: JSON.stringify({ p_limit: 8 }),
      signal: AbortSignal.timeout(15000),
    });
    if (!queueResponse.ok) throw new Error(`The notification queue is unavailable (${queueResponse.status}).`);
    items = await queueResponse.json() as QueueItem[];
  } catch (error) {
    return respond({ error: error instanceof Error ? error.message : "Could not read the notification queue." }, 502);
  }

  const groups = itemsByKind(items ?? []);
  if (groups.size === 0) return respond({ queued: 0, sent: 0 });

  // The rows are already stamped as notified, so anything thrown while the mail
  // is built must put them back — otherwise a payment alert is lost for good.
  let mailResponse: Response | null = null;
  try {
    mailResponse = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: { Authorization: `Bearer ${resendApiKey}`, "Content-Type": "application/json" },
      body: JSON.stringify({
        from,
        to: [to],
        subject: subjectLine(groups),
        html: renderHtml(groups),
        text: renderText(groups),
      }),
      signal: AbortSignal.timeout(20000),
    });
  } catch (error) {
    await requeue(items);
    return respond({ error: `The digest mail could not be prepared. Rows returned to the queue. ${error instanceof Error ? error.message : ""}` }, 502);
  }

  if (!mailResponse || !mailResponse.ok) {
    const detail = mailResponse ? (await mailResponse.text()).slice(0, 300) : "Resend could not be reached.";
    await requeue(items);
    return respond({ error: `The notification mail failed. Rows returned to the queue. ${detail}` }, 502);
  }

  const payload = await mailResponse.json() as { id?: string };
  return respond({ queued: items.length, sent: 1, email_id: payload.id ?? null, kinds: [...groups.keys()] });
});
