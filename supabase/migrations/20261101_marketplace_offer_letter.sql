-- A selected mentor gets a real letter, not just a badge flip: approving an
-- application queues a formal offer mail to the applicant, and the same queue
-- carries anything else the app must post on its own behalf.
--
-- The marketplace also grows a third shelf. Alongside a service (their time) and
-- a digital product (a file), a mentor can now run a webinar - a scheduled
-- session with a join link, sold at the price they set.

-- ── Webinars: a scheduled live session a mentor sells ───────────────────────
alter table public.mentor_products drop constraint if exists mentor_products_kind_check;
alter table public.mentor_products add constraint mentor_products_kind_check
  check (kind in ('service', 'digital', 'webinar'));

alter table public.mentor_products
  add column if not exists starts_at timestamptz,
  add column if not exists room_url text not null default '' check (char_length(room_url) <= 500);

-- A webinar without a time cannot be attended, so it cannot be published.
create or replace function public.mentor_products_guard()
returns trigger
language plpgsql
as $fn$
declare
  v_mentor public.mentors;
begin
  select * into v_mentor from public.mentors where user_id = new.mentor_user_id;
  if not found then
    raise exception 'Apply for a mentor account before publishing a product' using errcode = '42501';
  end if;
  if array_length(new.includes, 1) > 12 then
    raise exception 'Keep a product to 12 bullet points' using errcode = '22023';
  end if;
  if new.kind = 'webinar' and new.starts_at is null then
    raise exception 'A webinar needs a start time' using errcode = '22023';
  end if;
  if new.kind <> 'webinar' then
    new.starts_at := null;
    new.room_url := '';
  end if;
  new.updated_at := now();
  return new;
end;
$fn$;

