-- ── The outbox: letters the app posts on its own ────────────────────────────
create table if not exists public.email_outbox (
  id bigint generated by default as identity primary key,
  to_address text not null check (to_address ~* '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'),
  recipient_name text not null default '',
  subject text not null check (char_length(subject) between 4 and 200),
  body_html text not null,
  body_text text not null,
  kind text not null default 'offer_letter' check (kind in ('offer_letter', 'note')),
  ref text not null default '',
  status text not null default 'queued' check (status in ('queued', 'sent', 'failed')),
  attempts integer not null default 0,
  error text not null default '',
  queued_at timestamptz not null default now(),
  sent_at timestamptz
);

create index if not exists email_outbox_status_idx on public.email_outbox (status, queued_at);

alter table public.email_outbox enable row level security;

-- Nothing in the outbox is readable from a browser; the notification job is the
-- only caller and it runs with the service key.
create policy "Outbox stays server-side" on public.email_outbox
  for select to authenticated using (false);

-- Atomically claim the queued letters so two scheduler runs never send the same
-- offer letter twice.
create or replace function public.email_outbox_claim(p_limit integer default 6)
returns table (
  id bigint,
  to_address text,
  recipient_name text,
  subject text,
  body_html text,
  body_text text,
  kind text,
  ref text
)
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_limit integer := least(greatest(coalesce(p_limit, 6), 1), 20);
begin
  perform pg_advisory_xact_lock(hashtext('codexsheet-email-outbox'));

  return query
  with picked as (
    update public.email_outbox stamped
      set attempts = stamped.attempts + 1
    where stamped.id in (
      select pending.id
      from public.email_outbox pending
      where pending.status = 'queued'
      order by pending.queued_at
      limit v_limit
      for update of pending skip locked
    )
    returning stamped.id, stamped.to_address, stamped.recipient_name, stamped.subject,
      stamped.body_html, stamped.body_text, stamped.kind, stamped.ref
  )
  select picked.id, picked.to_address, picked.recipient_name, picked.subject,
    picked.body_html, picked.body_text, picked.kind, picked.ref
  from picked;
end;
$fn$;

revoke all on function public.email_outbox_claim(integer) from public, anon;
grant execute on function public.email_outbox_claim(integer) to service_role;

create or replace function public.email_outbox_result(p_id bigint, p_sent boolean, p_error text default '')
returns void
language plpgsql
security definer
set search_path = public
as $fn$
begin
  update public.email_outbox
    set status = case when p_sent then 'sent' else 'failed' end,
        sent_at = case when p_sent then now() else sent_at end,
        error = case when p_sent then '' else left(coalesce(p_error, 'unknown error'), 400) end
  where id = p_id;
end;
$fn$;

revoke all on function public.email_outbox_result(bigint, boolean, text) from public, anon;
grant execute on function public.email_outbox_result(bigint, boolean, text) to service_role;

-- A letter that failed is put back for the next run, the same way the payment
-- digest requeues itself when Resend is unreachable.
create or replace function public.email_outbox_retry(p_ids bigint[])
returns integer
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_count integer;
begin
  update public.email_outbox set status = 'queued' where id = any (coalesce(p_ids, array[]::bigint[]));
  get diagnostics v_count = row_count;
  return v_count;
end;
$fn$;

revoke all on function public.email_outbox_retry(bigint[]) from public, anon;
grant execute on function public.email_outbox_retry(bigint[]) to service_role;

