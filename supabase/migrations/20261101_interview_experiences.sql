-- CodexSheet has no interview-experience data of its own, and nothing worth
-- trusting can be lifted off the internet: every dataset that looked usable is a
-- scrape of GeeksforGeeks, Glassdoor or LeetCode Discuss, which means the text
-- belongs to somebody else and no uploader's "CC0" label changes that.
--
-- So the real version of this feature is the one candidates write themselves,
-- the same way the feedback pipeline works. A row only exists because a person
-- answered "yes, publish this" on the form, and it only reaches the public page
-- after a platform mentor has read it.

-- ── The experiences ────────────────────────────────────────────────────────
create table if not exists public.interview_experiences (
  id bigint generated by default as identity primary key,
  company text not null check (char_length(btrim(company)) between 2 and 60),
  role text not null check (char_length(btrim(role)) between 2 and 80),
  location text not null default '' check (char_length(location) <= 80),
  interview_year int not null check (interview_year between 2015 and 2100),
  outcome text not null check (outcome in ('selected', 'rejected', 'ongoing', 'withdrew')),
  -- [{ "name": "Online assessment", "questions": ["...", "..."] }]
  rounds jsonb not null default '[]'::jsonb,
  narrative text not null check (char_length(btrim(narrative)) between 40 and 4000),
  -- Without an explicit grant nothing is publishable, and the check has no
  -- default so a form that forgets the box cannot insert at all.
  consent boolean not null check (consent),
  -- Shown under the card. An email is never published.
  handle text not null default '' check (char_length(handle) <= 60),
  user_id text not null default '' check (char_length(user_id) <= 120),
  visible boolean not null default false,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  constraint interview_experiences_rounds_is_array check (jsonb_typeof(rounds) = 'array')
);

create index if not exists interview_experiences_company_idx
  on public.interview_experiences (lower(company), created_at desc)
  where visible;

create index if not exists interview_experiences_review_idx
  on public.interview_experiences (visible, created_at);

alter table public.interview_experiences enable row level security;

-- ── Write guard ────────────────────────────────────────────────────────────
-- An anonymous insert is a string from a stranger, so the trigger, not the form,
-- decides what a row is allowed to look like: trimmed text, a bounded number of
-- rounds, and no surprise keys in the rounds payload. Once a row exists its story
-- is frozen - the only thing a reviewer may change is whether the public sees it.
create or replace function public.interview_experiences_guard()
returns trigger
language plpgsql
as $fn$
declare
  entry jsonb;
  cleaned jsonb := '[]'::jsonb;
begin
  new.company := btrim(new.company);
  new.role := btrim(new.role);
  new.location := btrim(new.location);
  new.handle := btrim(new.handle);
  new.narrative := btrim(new.narrative);

  if jsonb_typeof(new.rounds) <> 'array' then
    raise exception 'the rounds have to be a list';
  end if;

  if new.rounds <> '[]'::jsonb then
    for entry in select * from jsonb_array_elements(new.rounds) limit 12 loop
      if jsonb_typeof(entry) <> 'object'
         or coalesce(jsonb_typeof(entry -> 'name'), '') <> 'string'
         or char_length(btrim(entry ->> 'name')) = 0
         or char_length(btrim(entry ->> 'name')) > 60 then
        raise exception 'a round needs a name of 1 to 60 characters';
      end if;

      cleaned := cleaned || jsonb_build_object(
        'name', btrim(entry ->> 'name'),
        'questions', case jsonb_typeof(entry -> 'questions')
          when 'array' then (
            select coalesce(jsonb_agg(btrim(q)), '[]'::jsonb)
            from jsonb_array_elements_text(entry -> 'questions') as q
            where char_length(btrim(q)) between 4 and 400
            limit 25
          )
          else '[]'::jsonb
        end
      );
    end loop;
    new.rounds := cleaned;
  end if;

  if tg_op = 'UPDATE' and not public.is_workspace_mentor() then
    raise exception 'only a platform mentor reviews an experience';
  end if;

  if tg_op = 'UPDATE' then
    new.company := old.company;
    new.role := old.role;
    new.location := old.location;
    new.interview_year := old.interview_year;
    new.outcome := old.outcome;
    new.rounds := old.rounds;
    new.narrative := old.narrative;
    new.consent := old.consent;
    new.handle := old.handle;
    new.user_id := old.user_id;
    new.created_at := old.created_at;
    new.reviewed_at := now();
  end if;

  return new;
end;
$fn$;

drop trigger if exists interview_experiences_guard on public.interview_experiences;
create trigger interview_experiences_guard
  before insert or update on public.interview_experiences
  for each row execute function public.interview_experiences_guard();

-- ── Who may read what ──────────────────────────────────────────────────────
drop policy if exists "Published experiences are public" on public.interview_experiences;
drop policy if exists "Anyone may offer an experience" on public.interview_experiences;
drop policy if exists "Platform mentors review the queue" on public.interview_experiences;

-- The public page reads published rows. A signed-in student can always read what
-- they offered, published or not, and a platform mentor reads everything so the
-- review queue has rows to work through.
--
-- The "their own row" arm has to demand a real subject claim first. An anonymous
-- submission lands with user_id = '', and a reader with no login also resolves to
-- '', so a bare comparison would hand every stranger the unpublished queue.
create policy "Published experiences are public"
  on public.interview_experiences for select to anon, authenticated
  using (
    visible
    or (coalesce(auth.jwt() ->> 'sub', '') <> '' and user_id = (auth.jwt() ->> 'sub'))
    or public.is_workspace_mentor()
  );

-- Offering one is open to a stranger, but the consent column has no default, so a
-- form that skips the tick box fails the check.
create policy "Anyone may offer an experience"
  on public.interview_experiences for insert to anon, authenticated
  with check (consent);

create policy "Platform mentors review the queue"
  on public.interview_experiences for update to authenticated
  using (public.is_workspace_mentor())
  with check (public.is_workspace_mentor());

-- No delete policy exists on purpose: taking a row out is a service-key or
-- console action, never something a request from a browser can ask for.
revoke all on public.interview_experiences from anon, authenticated;
grant select, insert, update on public.interview_experiences to anon, authenticated;

-- The review queue is a plain select through RLS, and PostgREST reaches it as the
-- anon role when nobody is signed in, so the function that decides "is this a
-- platform mentor" has to be callable by both roles.
grant execute on function public.is_workspace_mentor() to anon, authenticated;
