-- so anon is revoked by name on every function below.
revoke all on function public.student_directory(integer, text) from public, anon;
grant execute on function public.student_directory(integer, text) to authenticated;

-- ── One student's page ─────────────────────────────────────────────────────
-- Passing nothing gives you your own, which is how the rail opens.
create or replace function public.student_profile(p_user_id text default null)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_target text := btrim(coalesce(p_user_id, v_self));
  v_row public.profiles%rowtype;
  v_stats jsonb;
begin
  if v_self = '' then
    raise exception 'Sign in to see student profiles' using errcode = '42501';
  end if;

  select * into v_row from public.profiles pr where pr.user_id = v_target;
  if not found then
    raise exception 'No such student' using errcode = 'P0002';
  end if;

  v_stats := public.student_stats(v_target);

  return jsonb_build_object(
    'userId', v_row.user_id,
    'displayName', coalesce(nullif(btrim(v_row.display_name), ''), 'CodexSheet student'),
    'username', nullif(btrim(coalesce(v_row.username, '')), ''),
    'bio', coalesce(btrim(v_row.bio), ''),
    'joinedAt', v_row.created_at,
    'solved', v_stats -> 'solved',
    'xp', v_stats -> 'xp',
    'rankTitle', public.dsa_rank_title(coalesce((v_stats ->> 'xp')::integer, 0)),
    'lastSolvedAt', v_stats -> 'lastSolvedAt',
    'patterns', v_stats -> 'patterns',
    'followers', (select count(*)::integer from public.student_follows f where f.following_id = v_target),
    'following', (select count(*)::integer from public.student_follows f where f.follower_id = v_target),
    'followsYou', exists (select 1 from public.student_follows f where f.follower_id = v_target and f.following_id = v_self),
    'youFollow', exists (select 1 from public.student_follows f where f.follower_id = v_self and f.following_id = v_target),
    'isMe', v_target = v_self,
    -- The thread the two of you already share, if any. Looking at your own page
    -- finds no thread, because a chat is always between two different students.
    'chatId', case when v_target = v_self then null else (
      select chat.id from public.student_chats chat
      where v_self in (chat.user_a, chat.user_b)
        and v_target in (chat.user_a, chat.user_b)
      limit 1
    ) end
  );
end;
$fn$;

revoke all on function public.student_profile(text) from public, anon;
grant execute on function public.student_profile(text) to authenticated;

-- ── Follow and unfollow ────────────────────────────────────────────────────
create or replace function public.student_set_follow(p_target_id text, p_follow boolean)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_target text := btrim(coalesce(p_target_id, ''));
begin
  if v_self = '' then
    raise exception 'Sign in to follow students' using errcode = '42501';
  end if;

  if v_target = v_self then
    raise exception 'You are already on your own side' using errcode = '22023';
  end if;

  if not exists (select 1 from public.profiles pr where pr.user_id = v_target) then
    raise exception 'No such student' using errcode = 'P0002';
  end if;

  if coalesce(p_follow, false) then
    insert into public.student_follows (follower_id, following_id)
    values (v_self, v_target)
    on conflict (follower_id, following_id) do nothing;
  else
    delete from public.student_follows link
      where link.follower_id = v_self and link.following_id = v_target;
  end if;

  return jsonb_build_object(
    'follows', coalesce(p_follow, false),
    'target', v_target,
    'followers', (select count(*)::integer from public.student_follows f where f.following_id = v_target),
    'following', (select count(*)::integer from public.student_follows f where f.follower_id = v_target)
  );
end;
$fn$;

revoke all on function public.student_set_follow(text, boolean) from public, anon;
grant execute on function public.student_set_follow(text, boolean) to authenticated;

-- Who follows this student, and who they follow. The card on a profile page.
create or replace function public.student_follow_list(p_user_id text default null, p_kind text default 'followers')
returns table (user_id text, display_name text, username text, since timestamptz)
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_target text := btrim(coalesce(p_user_id, v_self));
  v_kind text := case when lower(coalesce(p_kind, 'followers')) = 'following' then 'following' else 'followers' end;
begin
  if v_self = '' then
    return;
  end if;

  return query
  select link.other,
         public.student_name_of(link.other),
         (select nullif(btrim(pr.username), '') from public.profiles pr where pr.user_id = link.other),
         link.since
  from (
    select case when v_kind = 'followers' then f.follower_id else f.following_id end as other,
           f.created_at as since
    from public.student_follows f
    where (v_kind = 'followers' and f.following_id = v_target)
       or (v_kind = 'following' and f.follower_id = v_target)
  ) link
  order by link.since desc;
end;
$fn$;

revoke all on function public.student_follow_list(text, text) from public, anon;
grant execute on function public.student_follow_list(text, text) to authenticated;

-- ── The threads ────────────────────────────────────────────────────────────
-- Starting a thread is not a permission question, it is a rate question: one
-- student cannot open the whole directory in an afternoon.
create or replace function public.student_open_chat(p_peer_id text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_peer text := btrim(coalesce(p_peer_id, ''));
  v_lo text;
  v_hi text;
  v_chat bigint;
begin
  if v_self = '' then
    raise exception 'Sign in to message a student' using errcode = '42501';
  end if;

  if v_peer = '' or v_peer = v_self then
    raise exception 'There is nobody to message yet' using errcode = '22023';
  end if;

  if not exists (select 1 from public.profiles pr where pr.user_id = v_peer) then
    raise exception 'No such student' using errcode = 'P0002';
  end if;

  if (select count(*) from public.student_chats chat
      where chat.opened_by = v_self and chat.created_at > now() - interval '1 hour') >= 20 then
    raise exception 'You opened twenty threads in an hour. Wait for a reply before opening more.'
      using errcode = '42901';
  end if;

  v_lo := least(v_self, v_peer);
  v_hi := greatest(v_self, v_peer);

  insert into public.student_chats (user_a, user_b, opened_by)
  values (v_lo, v_hi, v_self)
  on conflict (user_a, user_b) do nothing
  returning student_chats.id into v_chat;

  if not found then
    select chat.id into strict v_chat from public.student_chats chat
      where chat.user_a = v_lo and chat.user_b = v_hi;
  end if;

  return jsonb_build_object('chat', v_chat, 'peer', v_peer, 'peerName', public.student_name_of(v_peer));
end;
$fn$;

revoke all on function public.student_open_chat(text) from public, anon;
grant execute on function public.student_open_chat(text) to authenticated;

-- The inbox: every thread with the last message and what you have not read.
create or replace function public.student_dm_threads()
returns table (
  chat_id bigint,
  peer_id text,
  display_name text,
  username text,
  last_message text,
  last_from text,
  last_message_at timestamptz,
  unread integer,
  follows_you boolean,
  you_follow boolean
)
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
begin
  if v_self = '' then
    return;
  end if;

  return query
  select chat.id,
         other_student.id,
         public.student_name_of(other_student.id),
         (select nullif(btrim(pr.username), '') from public.profiles pr where pr.user_id = other_student.id),
         coalesce(latest.content, ''),
         latest.sender_id,
         coalesce(latest.created_at, chat.last_message_at),
         (select count(*)::integer
          from public.student_dm_messages m
          where m.chat_id = chat.id
            and m.sender_id <> v_self
            and m.id > coalesce((select receipt.last_read_id from public.student_dm_reads receipt
                                 where receipt.chat_id = chat.id and receipt.user_id = v_self), 0)),
         exists (select 1 from public.student_follows f where f.follower_id = other_student.id and f.following_id = v_self),
         exists (select 1 from public.student_follows f where f.follower_id = v_self and f.following_id = other_student.id)
  from public.student_chats chat
  cross join lateral (select case when chat.user_a = v_self then chat.user_b else chat.user_a end as id) other_student
  left join lateral (
    select m.content, m.sender_id, m.created_at
    from public.student_dm_messages m
    where m.chat_id = chat.id
    order by m.id desc
    limit 1
  ) latest on true
  where v_self in (chat.user_a, chat.user_b)
  order by 8 desc, 7 desc;
end;
$fn$;

revoke all on function public.student_dm_threads() from public, anon;
grant execute on function public.student_dm_threads() to authenticated;

-- One page of a thread, newest first; pass p_before to walk back in time.
create or replace function public.student_dm_history(
  p_chat_id bigint,
  p_before bigint default null,
  p_limit integer default 40
)
returns table (id bigint, from_id text, content text, created_at timestamptz)
language plpgsql
