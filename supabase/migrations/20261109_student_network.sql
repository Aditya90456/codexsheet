-- ── Helpers ────────────────────────────────────────────────────────────────
-- Is this student one of the two people on the other side of a thread?
create or replace function public.student_is_in_chat(p_chat_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.student_chats chat
    where chat.id = p_chat_id
      and coalesce(auth.jwt() ->> 'sub', '') in (chat.user_a, chat.user_b)
  );
$$;

revoke all on function public.student_is_in_chat(bigint) from public;
grant execute on function public.student_is_in_chat(bigint) to authenticated;

-- Sheet numbers for one student: how far they got, what it is worth, and the
-- three patterns they solve the most. Internal - the RPCs below shape the answer.
create or replace function public.student_stats(p_user_id text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'solved', (select count(*)::integer from public.dsa_progress done
               where done.user_id = p_user_id and done.status = 'Solved'),
    'xp', coalesce((select sum(public.dsa_xp_for(sheet.difficulty))::integer
                    from public.dsa_progress done
                    join public.dsa_sheet_problems sheet on sheet.number = done.problem_number
                    where done.user_id = p_user_id and done.status = 'Solved'), 0),
    'lastSolvedAt', (select max(done.updated_at) from public.dsa_progress done
                     where done.user_id = p_user_id and done.status = 'Solved'),
    'patterns', coalesce((
      select jsonb_agg(strong.pattern order by strong.solves desc)
      from (
        select sheet.pattern, count(*)::integer as solves
        from public.dsa_progress done
        join public.dsa_sheet_problems sheet on sheet.number = done.problem_number
        where done.user_id = p_user_id and done.status = 'Solved'
        group by sheet.pattern
        order by count(*) desc, sheet.pattern
        limit 3
      ) strong
    ), '[]'::jsonb)
  );
$$;

revoke all on function public.student_stats(text) from public, anon, authenticated;

-- The name a student sees. Never an email, even as a fallback - that is what
