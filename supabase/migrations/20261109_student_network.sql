-- ── One thread per pair of students ────────────────────────────────────────
-- user_a is always the smaller id, so two students can only ever have one chat
-- between them no matter who types first.
create table if not exists public.student_chats (
  id bigint generated by default as identity primary key,
  user_a text not null,
  user_b text not null,
  opened_by text not null,
  created_at timestamptz not null default now(),
  last_message_at timestamptz not null default now(),
  check (user_a < user_b),
  check (opened_by in (user_a, user_b))
);

create unique index if not exists student_chats_pair_uidx
  on public.student_chats (user_a, user_b);

create index if not exists student_chats_recent_idx
  on public.student_chats (last_message_at desc);

alter table public.student_chats
  drop constraint if exists student_chats_user_a_fkey;
alter table public.student_chats
  add constraint student_chats_user_a_fkey foreign key (user_a)
  references public.profiles (user_id) on delete cascade;

alter table public.student_chats
  drop constraint if exists student_chats_user_b_fkey;
alter table public.student_chats
  add constraint student_chats_user_b_fkey foreign key (user_b)
  references public.profiles (user_id) on delete cascade;

alter table public.student_chats enable row level security;

revoke all on table public.student_chats from anon, authenticated;

create table if not exists public.student_dm_messages (
  id bigint generated by default as identity primary key,
  chat_id bigint not null references public.student_chats(id) on delete cascade,
