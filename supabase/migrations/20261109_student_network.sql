-- ── The directory ──────────────────────────────────────────────────────────
-- Everyone signed in, ranked by who already follows you and then by XP, with
-- the two flags the follow button needs. p_query matches a name or a handle.
create or replace function public.student_directory(p_limit integer default 60, p_query text default '')
returns table (
  user_id text,
  display_name text,
  username text,
  bio text,
  solved integer,
  xp integer,
  rank_title text,
  followers integer,
  follows_you boolean,
  you_follow boolean,
  joined_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_limit integer := least(greatest(coalesce(p_limit, 60), 1), 100);
  v_query text := lower(btrim(coalesce(p_query, '')));
begin
  if v_self = '' then
    return;
  end if;

  return query
  with counted as (
    select pr.user_id,
           count(done.*)::integer as solved,
           coalesce(sum(public.dsa_xp_for(sheet.difficulty))::integer, 0) as xp
    from public.profiles pr
    left join public.dsa_progress done on done.user_id = pr.user_id and done.status = 'Solved'
    left join public.dsa_sheet_problems sheet on sheet.number = done.problem_number
    group by pr.user_id
  )
  select pr.user_id,
         coalesce(nullif(btrim(pr.display_name), ''), 'CodexSheet student'),
         nullif(btrim(pr.username), ''),
         coalesce(btrim(pr.bio), ''),
         counted.solved,
         counted.xp,
         public.dsa_rank_title(counted.xp),
         (select count(*)::integer from public.student_follows fans where fans.following_id = pr.user_id),
         exists (select 1 from public.student_follows f where f.follower_id = pr.user_id and f.following_id = v_self),
         exists (select 1 from public.student_follows f where f.follower_id = v_self and f.following_id = pr.user_id),
         pr.created_at
  from public.profiles pr
  join counted on counted.user_id = pr.user_id
  where pr.user_id <> v_self
    and coalesce(btrim(pr.user_id), '') <> ''
    and (v_query = '' or strpos(lower(coalesce(pr.display_name, '') || ' ' || coalesce(pr.username, '')), v_query) > 0)
  order by 9 desc, 6 desc, 11 asc
  limit v_limit;
end;
$fn$;

-- Supabase hands EXECUTE to the anon role through default privileges, and
