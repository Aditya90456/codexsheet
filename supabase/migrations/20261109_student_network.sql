-- Sending. This is where the stranger rule lives: no follow link between you
-- and nobody has answered you yet, so this is still your one message. Once they
-- reply, or once either of you follows the other, the thread is open for good.
create or replace function public.student_send_dm(p_chat_id bigint, p_content text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_peer text;
  v_content text := btrim(coalesce(p_content, ''));
  v_id bigint;
  v_at timestamptz;
  v_linked boolean;
begin
  if v_self = '' then
    raise exception 'Sign in to message a student' using errcode = '42501';
  end if;

  select case when chat.user_a = v_self then chat.user_b else chat.user_a end
    into v_peer
    from public.student_chats chat
   where chat.id = p_chat_id
     and v_self in (chat.user_a, chat.user_b);

  if v_peer is null then
    -- Same words whether the thread is somebody else's or does not exist, so a
    -- student cannot walk the ids to find out who talks to whom.
    raise exception 'That thread is not yours' using errcode = '42501';
  end if;

  if v_content = '' then
    raise exception 'Write something before you send it' using errcode = '22023';
  end if;

  if char_length(v_content) > 2000 then
    raise exception 'Keep a message under 2000 characters' using errcode = '22023';
  end if;

  if (select count(*) from public.student_dm_messages m
      where m.sender_id = v_self and m.created_at > now() - interval '1 minute') >= 12 then
    raise exception 'Slow down a little - a minute of typing is plenty.' using errcode = '42901';
  end if;

  v_linked := exists (
    select 1 from public.student_follows f
    where (f.follower_id = v_self and f.following_id = v_peer)
       or (f.follower_id = v_peer and f.following_id = v_self)
  );

  if not v_linked and not exists (
    -- The peer has answered at least once, so this stopped being a cold
    -- approach the moment they typed back.
    select 1 from public.student_dm_messages m
    where m.chat_id = p_chat_id and m.sender_id = v_peer
  ) and exists (
    select 1 from public.student_dm_messages m
    where m.chat_id = p_chat_id and m.sender_id = v_self
  ) then
    raise exception 'A student who does not follow you gets one message until they answer. Follow them to keep the thread open.'
      using errcode = '42501', hint = public.student_name_of(v_peer);
  end if;

  insert into public.student_dm_messages (chat_id, sender_id, content)
  values (p_chat_id, v_self, v_content)
  returning student_dm_messages.id, student_dm_messages.created_at into v_id, v_at;

  update public.student_chats chat
    set last_message_at = v_at
    where chat.id = p_chat_id;

  -- You have obviously read your own message.
  insert into public.student_dm_reads (chat_id, user_id, last_read_id, updated_at)
  values (p_chat_id, v_self, v_id, v_at)
  on conflict (chat_id, user_id) do update
    set last_read_id = greatest(student_dm_reads.last_read_id, excluded.last_read_id),
        updated_at = excluded.updated_at;

  return jsonb_build_object('id', v_id, 'chat', p_chat_id, 'from', v_self, 'content', v_content, 'at', v_at);
end;
$fn$;

revoke all on function public.student_send_dm(bigint, text) from public, anon;
grant execute on function public.student_send_dm(bigint, text) to authenticated;

create or replace function public.student_mark_read(p_chat_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
begin
  if not public.student_is_in_chat(p_chat_id) then
    raise exception 'That thread is not yours' using errcode = '42501';
  end if;

  insert into public.student_dm_reads (chat_id, user_id, last_read_id, updated_at)
  select p_chat_id, v_self, coalesce(max(m.id), 0), now()
  from public.student_dm_messages m
  where m.chat_id = p_chat_id
  on conflict (chat_id, user_id) do update
    set last_read_id = greatest(student_dm_reads.last_read_id, excluded.last_read_id),
        updated_at = excluded.updated_at;
end;
$fn$;

revoke all on function public.student_mark_read(bigint) from public, anon;
grant execute on function public.student_mark_read(bigint) to authenticated;

-- The badge on the nav rail.
create or replace function public.student_unread_dms()
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((
    select count(*)::integer
    from public.student_chats chat
    join public.student_dm_messages m on m.chat_id = chat.id
    where coalesce(auth.jwt() ->> 'sub', '') in (chat.user_a, chat.user_b)
      and m.sender_id <> coalesce(auth.jwt() ->> 'sub', '')
      and m.id > coalesce((select receipt.last_read_id from public.student_dm_reads receipt
                           where receipt.chat_id = chat.id
                             and receipt.user_id = coalesce(auth.jwt() ->> 'sub', '')), 0)
  ), 0);
$$;

revoke all on function public.student_unread_dms() from public, anon;
grant execute on function public.student_unread_dms() to authenticated;

-- ── Editing your own card ──────────────────────────────────────────────────
-- The only write a student makes to profiles. A null argument means "leave it",
-- an empty username means "drop the handle".
create or replace function public.student_update_profile(
  p_display_name text default null,
  p_username text default null,
  p_bio text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_name text := btrim(coalesce(p_display_name, ''));
  v_handle text := lower(btrim(coalesce(p_username, '')));
  v_bio text := btrim(coalesce(p_bio, ''));
begin
  if v_self = '' then
    raise exception 'Sign in to edit your profile' using errcode = '42501';
  end if;

  if p_display_name is not null then
    if v_name = '' or char_length(v_name) > 40 then
      raise exception 'A name between 1 and 40 characters' using errcode = '22023';
    end if;
  end if;

  if p_username is not null and v_handle <> '' and v_handle !~* '^[a-z0-9_]{3,20}$' then
    raise exception 'A handle is 3-20 characters: a-z, 0-9 and underscore' using errcode = '22023', hint = v_handle;
  end if;

  if p_username is not null and v_handle <> '' and exists (
    select 1 from public.profiles pr
    where lower(pr.username) = v_handle and pr.user_id <> v_self and coalesce(btrim(pr.username), '') <> ''
  ) then
    raise exception 'That handle already belongs to another student' using errcode = '23505', hint = v_handle;
  end if;

  if char_length(v_bio) > 200 then
    raise exception 'Keep the line about you under 200 characters' using errcode = '22023';
  end if;

  update public.profiles pr
    set display_name = case when p_display_name is not null then v_name else pr.display_name end,
        username = case when p_username is not null then nullif(v_handle, '') else pr.username end,
        bio = case when p_bio is not null then v_bio else coalesce(pr.bio, '') end,
        updated_at = now()
    where pr.user_id = v_self;

  if not found then
    insert into public.profiles (user_id, display_name, username, bio)
    values (v_self, coalesce(nullif(v_name, ''), 'CodexSheet student'), nullif(v_handle, ''), v_bio)
    on conflict (user_id) do nothing;
  end if;

  return public.student_profile(v_self);
end;
$fn$;

revoke all on function public.student_update_profile(text, text, text) from public, anon;
grant execute on function public.student_update_profile(text, text, text) to authenticated;

