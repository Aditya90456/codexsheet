-- ── The student network ────────────────────────────────────────────────────
-- CodexSheet students get a place to find each other, follow each other and
-- talk one to one, the way a social network works but with only students on it.
--
-- Three rules hold the whole thing together:
--   1. Following is public and free - one tap, no approval, no feed to feed.
--   2. A private thread is opened by a message, not by a request. Anyone signed
--      in can start one, so nobody has to wait to ask a doubt.
--   3. A stranger gets one message. Until the other student replies - or either
--      of you follows the other - the thread stays shut. That is the whole spam
--      defence, and it is the same shape Facebook uses for message requests.
--
-- Everything the client touches goes through a SECURITY DEFINER function, so no
-- table grant has to widen and no student can read another student's email. The
-- profile columns added below are written only by student_update_profile().
--
-- public.profiles.username is pinned here as well. The leaderboard RPC from
-- 20261101_dsa_leaderboard_certificates.sql selects it, and the live database
-- has it, but no migration in this folder ever created it - so a rebuild from
-- these files would have broken /leaderboard. `if not exists` keeps this a
-- no-op on the live project. `bio` is genuinely new.

-- ── What a student can say about themselves ────────────────────────────────
alter table public.profiles
  add column if not exists username text;

alter table public.profiles
  add column if not exists bio text not null default '';

-- The handle has to be unique, but the column is older than this file and real
-- students already wrote into it. If two of them share a handle the index cannot
-- be built, and the rest of the network is worth more than the index - so this
-- says what clashed and moves on instead of rolling the whole paste back.
-- student_update_profile() still refuses a handle that is taken.
do $$
declare
  v_clash text;
begin
  if exists (
    select 1 from pg_class
    where relname = 'profiles_username_uidx' and relnamespace = 'public'::regnamespace
  ) then
    return;
  end if;

  select string_agg(format('%s x %s', handle, n), ', ')
    into v_clash
    from (
      select lower(btrim(username)) as handle, count(*)::int as n
      from public.profiles
      where coalesce(btrim(username), '') <> ''
      group by 1
      having count(*) > 1
      order by 2 desc, 1
      limit 5
    ) shared;

  if v_clash is not null then
    raise notice 'profiles_username_uidx was not created - these handles are already shared: %', v_clash;
    return;
  end if;

  create unique index profiles_username_uidx
    on public.profiles (lower(username))
    where coalesce(btrim(username), '') <> '';
end;
$$;

-- ── Who follows whom ───────────────────────────────────────────────────────
create table if not exists public.student_follows (
  follower_id text not null,
  following_id text not null,
  created_at timestamptz not null default now(),
  primary key (follower_id, following_id),
  check (follower_id <> following_id),
  check (coalesce(btrim(follower_id), '') <> '' and coalesce(btrim(following_id), '') <> '')
);

create index if not exists student_follows_target_idx
  on public.student_follows (following_id, created_at desc);

