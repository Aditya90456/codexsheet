-- ── The CodexSheet Network: sharing what you wrote ─────────────────────────
-- The follow + DM migration (20261109_student_network.sql) gave students a way
-- to find each other. This is the part they were looking for: a board where a
-- student posts the code they just wrote - the sliding-window version that finally
-- worked, the DP table they drew on the whiteboard - and the rest of the batch
-- likes it, dislikes it, or asks why line 14 is there.
--
-- Four rules, all of them the same shape as the ones next door:
--   1. Code is the post. A caption helps but a share without code is a status
--      update, and this is not that.
--   2. One reaction per student per post - like or dislike, switchable, and a
--      dislike says nothing except a number. Nobody is told who disliked them,
--      so the counts stay honest without turning into a scoreboard of shame.
--   3. Comments are the conversation. Anyone signed in can comment on anyone's
--      post; the author is the only one who can delete one of theirs.
--   4. You can only take back what you posted.
--
-- As before, the client touches no table directly: every read and write goes
-- through a SECURITY DEFINER function so the narrow column grants on profiles
-- never have to widen. Posts and comments are published for realtime; reactions
-- deliberately are not, because a reaction row says who disliked whom.
--
-- Paste 20261109_student_network.sql first: this file calls student_name_of()
-- and the follows table from there.

-- Said in Postgres's own voice, so the order can never be guessed wrong. Without
-- it the SQL functions below fail on an unknown student_name_of(text) and the
-- whole paste rolls back with no clue as to why.
do $$
begin
  if to_regclass('public.student_chats') is null
     or to_regclass('public.student_follows') is null
     or to_regprocedure('public.student_name_of(text)') is null then
    raise exception 'Paste 20261109_student_network.sql into this project first - the board is built on top of it.';
  end if;
  if not exists (
    select 1 from pg_attribute
    where attrelid = 'public.profiles'::regclass and attname = 'bio' and not attisdropped
  ) then
    raise exception 'public.profiles has no bio column, so 20261109_student_network.sql has not been pasted yet.';
  end if;
end;
$$;

-- ── The post ───────────────────────────────────────────────────────────────
create table if not exists public.student_posts (
  id bigint generated by default as identity primary key,
  author_id text not null,
  caption text not null default '' check (char_length(caption) <= 600),
  code text not null check (char_length(btrim(code)) between 1 and 20000),
  language text not null default 'python' check (language in ('python', 'javascript', 'java', 'cpp')),
  problem_number integer check (problem_number between 1 and 250),
  created_at timestamptz not null default now()
);

create index if not exists student_posts_recent_idx
  on public.student_posts (id desc);

create index if not exists student_posts_author_idx
  on public.student_posts (author_id, id desc);

alter table public.student_posts
  drop constraint if exists student_posts_author_id_fkey;
alter table public.student_posts
  add constraint student_posts_author_id_fkey foreign key (author_id)
  references public.profiles (user_id) on delete cascade;

alter table public.student_posts enable row level security;

-- A post is as public inside the network as a solved problem on the leaderboard,
-- so the read policy is "signed in and it is still there". Writing is not a
-- table grant at all - student_create_post() is the only way in.
drop policy if exists "Students read the board" on public.student_posts;
create policy "Students read the board"
  on public.student_posts for select to authenticated
  using (true);

-- Supabase's default privileges hand EVERY new table in public to anon and to
-- authenticated in full, and a later `grant select` only adds to that. Both
-- roles are revoked by name first, so the only thing the client can do to this
-- table is read it.
revoke all on table public.student_posts from anon, authenticated;
grant select on public.student_posts to authenticated;

-- ── Like and dislike ───────────────────────────────────────────────────────
create table if not exists public.student_post_reactions (
  post_id bigint not null references public.student_posts(id) on delete cascade,
  user_id text not null,
  kind text not null check (kind in ('like', 'dislike')),
  updated_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

alter table public.student_post_reactions
  drop constraint if exists student_post_reactions_user_id_fkey;
alter table public.student_post_reactions
  add constraint student_post_reactions_user_id_fkey foreign key (user_id)
  references public.profiles (user_id) on delete cascade;

create index if not exists student_post_reactions_post_idx
  on public.student_post_reactions (post_id, kind);

alter table public.student_post_reactions enable row level security;

-- No grant, no policy: who liked what is only ever returned as a count, plus
-- your own reaction, from the functions below.
revoke all on table public.student_post_reactions from anon, authenticated;

-- ── The comments ───────────────────────────────────────────────────────────
create table if not exists public.student_post_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.student_posts(id) on delete cascade,
  author_id text not null,
  content text not null check (char_length(btrim(content)) between 1 and 1500),
  created_at timestamptz not null default now()
);

create index if not exists student_post_comments_post_idx
  on public.student_post_comments (post_id, id desc);

alter table public.student_post_comments
