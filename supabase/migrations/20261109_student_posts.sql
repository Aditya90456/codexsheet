-- ── How much of the board a student has read ───────────────────────────────
-- The nav badge wants "new since you last looked", not a per-thread receipt:
-- one row per student, moved forward whenever the board is opened.
create table if not exists public.student_feed_views (
  user_id text primary key,
  last_post_id bigint not null default 0,
  updated_at timestamptz not null default now()
);

alter table public.student_feed_views enable row level security;

revoke all on table public.student_feed_views from anon, authenticated;

create or replace function public.student_unread_posts()
returns integer
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_seen bigint;
begin
  if v_self = '' then
    return 0;
  end if;

  select coalesce(v.last_post_id, 0) into v_seen
    from public.student_feed_views v where v.user_id = v_self;

  return coalesce((
    select count(*)::integer from public.student_posts p
     where p.id > coalesce(v_seen, 0) and p.author_id <> v_self
  ), 0);
end;
$fn$;

revoke all on function public.student_unread_posts() from public, anon;
grant execute on function public.student_unread_posts() to authenticated;

create or replace function public.student_mark_feed_seen()
returns void
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
begin
  if v_self = '' then
    raise exception 'Sign in first' using errcode = '42501';
  end if;

  insert into public.student_feed_views (user_id, last_post_id, updated_at)
  select v_self, coalesce(max(p.id), 0), now() from public.student_posts p
  on conflict (user_id) do update
    set last_post_id = greatest(student_feed_views.last_post_id, excluded.last_post_id),
        updated_at = excluded.updated_at;
end;
$fn$;

revoke all on function public.student_mark_feed_seen() from public, anon;
grant execute on function public.student_mark_feed_seen() to authenticated;

-- ── Live board ─────────────────────────────────────────────────────────────
-- New posts and new comments arrive as they happen. Reactions stay off the wire
-- on purpose: a reaction row names the student who disliked you.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'student_posts'
  ) then
    alter publication supabase_realtime add table public.student_posts;
  end if;

  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'student_post_comments'
  ) then
    alter publication supabase_realtime add table public.student_post_comments;
  end if;
end;
$$;
