alter table public.student_post_comments
  add constraint student_post_comments_author_id_fkey foreign key (author_id)
  references public.profiles (user_id) on delete cascade;

alter table public.student_post_comments enable row level security;

drop policy if exists "Students read the comments" on public.student_post_comments;
create policy "Students read the comments"
  on public.student_post_comments for select to authenticated
  using (true);

revoke all on table public.student_post_comments from anon, authenticated;
grant select on public.student_post_comments to authenticated;

-- ── One post, in the shape the client wants ────────────────────────────────
-- The board, a single post and the answer to a reaction all describe a post the
-- same way, so it is written once. Internal: revoked below, called by the
-- SECURITY DEFINER functions that run as the owner.
create or replace function public.student_post_row(p_post_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select to_jsonb(post_row)
  from (
    select p.id,
           p.author_id                                as "userId",
           public.student_name_of(p.author_id)        as "displayName",
           coalesce(nullif(btrim(pr.username), ''), '') as username,
           pr.created_at                              as "joinedAt",
           (select count(*)::integer from public.dsa_progress done
             where done.user_id = p.author_id and done.status = 'Solved') as solved,
           public.dsa_rank_title(
             coalesce((select sum(public.dsa_xp_for(sheet.difficulty))::integer
                       from public.dsa_progress done
                       join public.dsa_sheet_problems sheet on sheet.number = done.problem_number
                       where done.user_id = p.author_id and done.status = 'Solved'), 0)
           )                                          as "rankTitle",
           p.caption,
           p.code,
           p.language,
           p.problem_number                           as "problemNumber",
           (select sheet.title from public.dsa_sheet_problems sheet
             where sheet.number = p.problem_number)   as "problemTitle",
           p.created_at                               as "createdAt",
           coalesce((select count(*)::integer from public.student_post_reactions like_row
                      where like_row.post_id = p.id and like_row.kind = 'like'), 0)    as likes,
           coalesce((select count(*)::integer from public.student_post_reactions hate_row
                      where hate_row.post_id = p.id and hate_row.kind = 'dislike'), 0) as dislikes,
           coalesce((select count(*)::integer from public.student_post_comments c
                      where c.post_id = p.id), 0)                                       as comments,
           coalesce((select mine.kind from public.student_post_reactions mine
                      where mine.post_id = p.id
                        and mine.user_id = coalesce(auth.jwt() ->> 'sub', '')), '')     as "myReaction",
           exists (select 1 from public.student_follows f
                    where f.follower_id = p.author_id
                      and f.following_id = coalesce(auth.jwt() ->> 'sub', ''))          as "followsYou",
           exists (select 1 from public.student_follows f
                    where f.follower_id = coalesce(auth.jwt() ->> 'sub', '')
                      and f.following_id = p.author_id)                                 as "youFollow",
           p.author_id = coalesce(auth.jwt() ->> 'sub', '')                             as "isMine"
      from public.student_posts p
      left join public.profiles pr on pr.user_id = p.author_id
     where p.id = p_post_id
  ) post_row;
$$;

revoke all on function public.student_post_row(bigint) from public, anon, authenticated;

-- ── Posting ────────────────────────────────────────────────────────────────
create or replace function public.student_create_post(
  p_code text,
  p_caption text default '',
  p_language text default 'python',
  p_problem_number integer default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_code text := btrim(coalesce(p_code, ''));
  v_caption text := btrim(coalesce(p_caption, ''));
  v_language text := lower(btrim(coalesce(p_language, 'python')));
  v_problem integer := p_problem_number;
  v_id bigint;
begin
  if v_self = '' then
    raise exception 'Sign in to share your code' using errcode = '42501';
  end if;

  if v_code = '' then
    raise exception 'The code is the post - paste the solution you want feedback on.'
      using errcode = '22023';
  end if;

  if char_length(v_code) > 20000 then
    raise exception 'Keep a share under 20000 characters - post the function, not the whole file.'
      using errcode = '22023';
  end if;

  if char_length(v_caption) > 600 then
    raise exception 'Keep the line above the code under 600 characters' using errcode = '22023';
  end if;

  if v_language not in ('python', 'javascript', 'java', 'cpp') then
    raise exception 'Python, JavaScript, Java or C++' using errcode = '22023', hint = v_language;
  end if;

  if v_problem is not null and not exists (
    select 1 from public.dsa_sheet_problems sheet where sheet.number = v_problem
  ) then
    raise exception 'There is no problem number that high on the sheet' using errcode = '22023';
  end if;

  if (select count(*) from public.student_posts p
      where p.author_id = v_self and p.created_at > now() - interval '1 hour') >= 10 then
    raise exception 'Ten shares an hour is a lot of code - give the batch time to read it.'
      using errcode = '42901';
  end if;

  insert into public.student_posts (author_id, caption, code, language, problem_number)
  values (v_self, v_caption, v_code, v_language, v_problem)
  returning student_posts.id into v_id;

  return public.student_post_row(v_id);
end;
$fn$;

revoke all on function public.student_create_post(text, text, text, integer) from public, anon;
grant execute on function public.student_create_post(text, text, text, integer) to authenticated;

-- ── The board ──────────────────────────────────────────────────────────────
-- Three tabs, one query. 'following' is the feed a student actually wants once
-- they have a few follows: their own work next to the people they chose.
create or replace function public.student_feed(
  p_tab text default 'all',
  p_before bigint default null,
  p_limit integer default 20
)
returns table (
  post jsonb,
  ordinal bigint
)
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_tab text := lower(btrim(coalesce(p_tab, 'all')));
  v_limit integer := least(greatest(coalesce(p_limit, 20), 1), 50);
begin
  if v_self = '' then
    return;
  end if;

  if v_tab not in ('all', 'following', 'mine') then
    v_tab := 'all';
  end if;

  return query
  select public.student_post_row(p.id) as post, p.id as ordinal
    from public.student_posts p
   where (p_before is null or p.id < p_before)
     and (
       v_tab = 'all'
       or (v_tab = 'mine' and p.author_id = v_self)
       or (v_tab = 'following' and (p.author_id = v_self or exists (
             select 1 from public.student_follows f
             where f.follower_id = v_self and f.following_id = p.author_id)))
     )
   order by p.id desc
   limit v_limit;
end;
$fn$;

revoke all on function public.student_feed(text, bigint, integer) from public, anon;
grant execute on function public.student_feed(text, bigint, integer) to authenticated;

-- ── One post with its comments ─────────────────────────────────────────────
-- The board carries counts; opening a post is what brings the conversation.
create or replace function public.student_post_detail(p_post_id bigint, p_limit integer default 60)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  v_post jsonb;
  v_limit integer := least(greatest(coalesce(p_limit, 60), 1), 200);
begin
  if coalesce(auth.jwt() ->> 'sub', '') = '' then
    raise exception 'Sign in to read the board' using errcode = '42501';
  end if;

  v_post := public.student_post_row(p_post_id);
  if v_post is null then
    raise exception 'That post is gone' using errcode = 'P0002';
  end if;

  return v_post || jsonb_build_object(
    'thread', coalesce((
      select jsonb_agg(jsonb_build_object(
               'id', picked.id,
               'userId', picked.author_id,
               'displayName', public.student_name_of(picked.author_id),
               'content', picked.content,
               'createdAt', picked.created_at,
               'isMine', picked.author_id = coalesce(auth.jwt() ->> 'sub', '')
             ) order by picked.id)
        from (
          -- The newest p_limit replies, then put back in reading order.
          select c.id, c.author_id, c.content, c.created_at
            from public.student_post_comments c
           where c.post_id = p_post_id
           order by c.id desc
           limit v_limit
        ) picked
    ), '[]'::jsonb)
  );
end;
$fn$;

revoke all on function public.student_post_detail(bigint, integer) from public, anon;
grant execute on function public.student_post_detail(bigint, integer) to authenticated;

-- ── Liking, disliking, changing your mind ─────────────────────────────────
create or replace function public.student_react(p_post_id bigint, p_kind text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_kind text := lower(btrim(coalesce(p_kind, '')));
begin
  if v_self = '' then
    raise exception 'Sign in to react to a post' using errcode = '42501';
  end if;

  if v_kind not in ('like', 'dislike', 'none') then
    raise exception 'A reaction is a like, a dislike or none' using errcode = '22023', hint = v_kind;
  end if;

  if not exists (select 1 from public.student_posts p where p.id = p_post_id) then
    raise exception 'That post is gone' using errcode = 'P0002';
  end if;

  if v_kind = 'none' then
    delete from public.student_post_reactions r
      where r.post_id = p_post_id and r.user_id = v_self;
  else
    insert into public.student_post_reactions (post_id, user_id, kind)
    values (p_post_id, v_self, v_kind)
    on conflict (post_id, user_id) do update
      set kind = excluded.kind, updated_at = now();
  end if;

  return public.student_post_row(p_post_id);
end;
$fn$;

revoke all on function public.student_react(bigint, text) from public, anon;
grant execute on function public.student_react(bigint, text) to authenticated;

-- ── Commenting ─────────────────────────────────────────────────────────────
create or replace function public.student_comment(p_post_id bigint, p_content text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
  v_text text := btrim(coalesce(p_content, ''));
  v_id bigint;
  v_at timestamptz;
begin
  if v_self = '' then
    raise exception 'Sign in to comment' using errcode = '42501';
  end if;

  if v_text = '' then
    raise exception 'Write something before you send it' using errcode = '22023';
  end if;

  if char_length(v_text) > 1500 then
    raise exception 'Keep a comment under 1500 characters' using errcode = '22023';
  end if;

  if not exists (select 1 from public.student_posts p where p.id = p_post_id) then
    raise exception 'That post is gone' using errcode = 'P0002';
  end if;

  if (select count(*) from public.student_post_comments c
      where c.author_id = v_self and c.created_at > now() - interval '1 minute') >= 12 then
    raise exception 'Slow down a little - a minute of typing is plenty.' using errcode = '42901';
  end if;

  insert into public.student_post_comments (post_id, author_id, content)
  values (p_post_id, v_self, v_text)
  returning student_post_comments.id, student_post_comments.created_at into v_id, v_at;

  return jsonb_build_object(
    'post', public.student_post_row(p_post_id),
    'comment', jsonb_build_object(
      'id', v_id,
      'userId', v_self,
      'displayName', public.student_name_of(v_self),
      'content', v_text,
      'createdAt', v_at,
      'isMine', true
    )
  );
end;
$fn$;

revoke all on function public.student_comment(bigint, text) from public, anon;
grant execute on function public.student_comment(bigint, text) to authenticated;

-- ── Taking back what was yours ─────────────────────────────────────────────
-- Deleting a post takes its comments and reactions with it, which is what the
-- cascade is for. Nobody else's name is attached to your post, so nobody else
-- can be punished by your deletion.
create or replace function public.student_delete_post(p_post_id bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_self text := coalesce(auth.jwt() ->> 'sub', '');
begin
  if v_self = '' then
    raise exception 'Sign in to delete a post' using errcode = '42501';
  end if;

  delete from public.student_posts p
    where p.id = p_post_id and p.author_id = v_self;

  if not found then
    raise exception 'That is not your post to delete' using errcode = '42501';
  end if;

  return jsonb_build_object('deleted', p_post_id);
end;
$fn$;

revoke all on function public.student_delete_post(bigint) from public, anon;
grant execute on function public.student_delete_post(bigint) to authenticated;

-- A comment goes the same way, and the author of the post may not remove
