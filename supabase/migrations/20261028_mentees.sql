create or replace function public.is_workspace_mentor()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(bool_or(mentor.user_id = (auth.jwt() ->> 'sub')), false)
  from public.workspace_mentors mentor;
$$;

revoke all on function public.is_workspace_mentor() from public;
grant execute on function public.is_workspace_mentor() to anon, authenticated, service_role;

create table if not exists public.mentees (
  id bigint generated by default as identity primary key,
  reference text not null unique check (char_length(reference) between 6 and 40),
  user_id text not null default '',
  mentor_user_id text not null,
  plan text not null check (plan in ('one-to-one', 'ltm-3-months', 'ltm-6-months')),
  status text not null default 'active'
    check (status in ('active', 'paused', 'completed', 'cancelled')),
  student_name text not null check (char_length(student_name) between 1 and 120),
  contact text not null default '' check (char_length(contact) <= 160),
  weekly_slot text not null default '' check (char_length(weekly_slot) <= 120),
  notes text not null default '' check (char_length(notes) <= 2000),
  started_at timestamptz not null default now(),
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists mentees_user_idx on public.mentees (user_id, created_at desc);

alter table public.mentees enable row level security;

drop policy if exists "Mentees read their own record and mentors read all" on public.mentees;
drop policy if exists "Only mentors manage mentees" on public.mentees;

create policy "Mentees read their own record and mentors read all"
  on public.mentees for select to authenticated
  using (user_id = (auth.jwt() ->> 'sub') or public.is_workspace_mentor());

create policy "Only mentors manage mentees"
  on public.mentees for all to authenticated
  using (public.is_workspace_mentor())
  with check (public.is_workspace_mentor());

grant select, insert, update, delete on public.mentees to authenticated;
grant usage, select on sequence public.mentees_id_seq to authenticated;

-- Confirmed payments the mentor has not turned into mentees yet. Anonymous callers
-- get an empty set because the function checks the mentor list first.
create or replace function public.mentor_pending_orders()
returns table (
  reference text,
  plan text,
  amount numeric,
  student text,
  contact text,
  paytm_reference text,
  note text,
  user_id text,
  placed_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $fn$
begin
  if not public.is_workspace_mentor() then
    return;
  end if;

  return query
  select placed.reference, placed.plan, placed.amount, placed.buyer_name, placed.buyer_contact,
    placed.paytm_reference, placed.note, placed.user_id, placed.created_at
  from public.mentorship_orders placed
  where placed.status = 'awaiting'
    and placed.plan <> 'roadmap'
  order by placed.created_at
  limit 50;
end;
$fn$;

revoke all on function public.mentor_pending_orders() from public;
grant execute on function public.mentor_pending_orders() to authenticated, service_role;

-- Confirming a claim marks the payment confirmed and opens the mentee record in
-- one step, so a paid student can never be left half-processed.
create or replace function public.mentor_confirm_mentee(
  p_reference text,
  p_weekly_slot text default '',
  p_notes text default ''
)
returns bigint
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_order public.mentorship_orders;
  v_mentee_id bigint;
begin
  if not public.is_workspace_mentor() then
    raise exception 'Only mentors can confirm a payment' using errcode = '42501';
  end if;

  select * into strict v_order
  from public.mentorship_orders placed
  where trim(lower(placed.reference)) = trim(lower(coalesce(p_reference, '')));

  if v_order.plan = 'roadmap' then
    raise exception 'A roadmap download does not create a mentee' using errcode = '22023';
  end if;

  update public.mentorship_orders placed
    set status = 'confirmed', notified_at = coalesce(placed.notified_at, now()), updated_at = now()
  where placed.reference = v_order.reference;

  insert into public.mentees (
    reference, user_id, mentor_user_id, plan, status, student_name, contact, weekly_slot, notes,
    started_at, ends_at
  )
  values (
    v_order.reference, v_order.user_id, (auth.jwt() ->> 'sub'), v_order.plan, 'active',
    v_order.buyer_name, v_order.buyer_contact,
    coalesce(nullif(trim(p_weekly_slot), ''), case v_order.plan when 'one-to-one' then 'single session' else '' end),
    coalesce(nullif(trim(p_notes), ''), v_order.note),
    now(),
    case v_order.plan
      when 'ltm-3-months' then now() + interval '3 months'
      when 'ltm-6-months' then now() + interval '6 months'
    end
  )
  on conflict (reference) do update
    set user_id = coalesce(nullif(excluded.user_id, ''), public.mentees.user_id),
        status = 'active',
        weekly_slot = excluded.weekly_slot,
        notes = excluded.notes,
        ends_at = excluded.ends_at,
        updated_at = now()
  returning mentees.id into v_mentee_id;

  return v_mentee_id;
end;
$fn$;

revoke all on function public.mentor_confirm_mentee(text, text, text) from public;
grant execute on function public.mentor_confirm_mentee(text, text, text) to authenticated, service_role;

notify pgrst, 'reload schema';
