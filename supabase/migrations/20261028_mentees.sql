-- Mentees. A mentee is a student whose Paytm payment was confirmed, which is what
-- unlocks the private chat lane and the weekly session. Mentor rights come from a
-- seeded table, never from a hard-coded id in the app.

create table if not exists public.workspace_mentors (
  user_id text primary key,
  added_at timestamptz not null default now()
);

alter table public.workspace_mentors enable row level security;

drop policy if exists "Signed-in users can see the mentor list" on public.workspace_mentors;
create policy "Signed-in users can see the mentor list"
  on public.workspace_mentors for select to authenticated
  using (true);

grant select on public.workspace_mentors to authenticated;

