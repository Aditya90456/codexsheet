-- Mentorship payments. Students pay the personal Paytm UPI handle directly, so
-- this table only records the claim for manual confirmation against the Paytm
-- statement; no gateway and no card data ever reaches the app.
create table if not exists public.mentorship_orders (
  id bigint generated by default as identity primary key,
  reference text not null unique check (char_length(reference) between 6 and 40),
  plan text not null check (plan in ('one-to-one', 'ltm-3-months', 'ltm-6-months')),
  amount numeric(8, 2) not null check (amount > 0),
  buyer_name text not null check (char_length(buyer_name) between 1 and 120),
  buyer_contact text not null default '' check (char_length(buyer_contact) <= 160),
  paytm_reference text not null default '' check (char_length(paytm_reference) <= 80),
  status text not null default 'awaiting'
    check (status in ('awaiting', 'confirmed', 'delivered', 'cancelled')),
  user_id text not null default '',
  note text not null default '' check (char_length(note) <= 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (
    (plan = 'one-to-one' and amount = 19)
    or (plan = 'ltm-3-months' and amount = 100)
    or (plan = 'ltm-6-months' and amount = 499)
  )
);

create index if not exists mentorship_orders_status_idx
  on public.mentorship_orders (status, created_at desc);

alter table public.mentorship_orders enable row level security;

drop policy if exists "Students record mentorship payments" on public.mentorship_orders;
drop policy if exists "Mentorship orders stay private" on public.mentorship_orders;

-- Anyone may file a claim, signed in or not. Nothing is readable from the
-- browser except through the status function below, which returns no contact
-- details, so a reference code is the only way a student can check their own.
create policy "Students record mentorship payments"
  on public.mentorship_orders for insert to anon, authenticated
  with check (buyer_name <> '');

create policy "Mentorship orders stay private"
  on public.mentorship_orders for select to anon, authenticated
  using (false);

grant select, insert, update on public.mentorship_orders to authenticated;
grant insert on public.mentorship_orders to anon;
grant usage, select on sequence public.mentorship_orders_id_seq to anon, authenticated;

create or replace function public.mentorship_order_status(p_reference text)
returns table (reference text, plan text, amount numeric, status text, filed_at timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select placed.reference, placed.plan, placed.amount, placed.status, placed.created_at
  from public.mentorship_orders placed
  where trim(lower(placed.reference)) = trim(lower(coalesce(p_reference, '')));
$$;

revoke all on function public.mentorship_order_status(text) from public;
grant execute on function public.mentorship_order_status(text) to anon, authenticated;

notify pgrst, 'reload schema';
