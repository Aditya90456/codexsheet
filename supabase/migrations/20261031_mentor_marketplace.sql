-- The shop window: approved mentors and everything they have on sale.
create or replace function public.marketplace_catalog()
returns table (
  id bigint,
  slug text,
  kind text,
  title text,
  summary text,
  details text,
  includes text[],
  format text,
  price numeric,
  file_url text,
  unlocks_workspace boolean,
  mentor_user_id text,
  mentor_name text,
  mentor_headline text,
  mentor_city text,
  mentor_bio text,
  mentor_expertise text[],
  upi_id text,
  payee_name text
)
language sql
stable
security definer
set search_path = public
as $$
  select item.id, item.slug, item.kind, item.title, item.summary, item.details, item.includes,
    item.format, item.price, item.file_url, item.unlocks_workspace,
    owner.user_id, owner.display_name, owner.headline, owner.city, owner.bio, owner.expertise,
    owner.upi_id, owner.payee_name
  from public.mentor_products item
  join public.mentors owner on owner.user_id = item.mentor_user_id
  where owner.status = 'approved' and item.active
  order by item.created_at desc;
$$;

revoke all on function public.marketplace_catalog() from public;
grant execute on function public.marketplace_catalog() to anon, authenticated;

-- A claim is looked up by its reference code, with no contact details returned.
create or replace function public.market_order_status(p_reference text)
returns table (reference text, product_title text, seller_name text, amount numeric, status text, delivered boolean, filed_at timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select placed.reference, placed.product_title, placed.seller_name, placed.amount, placed.status,
    placed.status in ('delivered', 'confirmed'), placed.created_at
  from public.market_orders placed
  where trim(lower(placed.reference)) = trim(lower(coalesce(p_reference, '')));
$$;

