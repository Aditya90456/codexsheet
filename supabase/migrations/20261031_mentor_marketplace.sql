-- CodexSheet stops being a one-mentor shop. Any signed-in student can apply for
-- a mentor account, and an approved mentor publishes their own services and
-- digital products at prices they set themselves.
--
-- Money still never touches a gateway: every product is paid to the MENTOR'S OWN
-- UPI handle, so each mentor renders a different QR code, and this app only
-- records the claim for that mentor to confirm against their own statement.
-- Aditya's Family Pass and mentorship_orders are untouched and stay his.

-- ── Mentor accounts ─────────────────────────────────────────────────────────
create table if not exists public.mentors (
  id bigint generated by default as identity primary key,
  user_id text not null unique check (char_length(user_id) between 1 and 120),
  email text not null default '' check (char_length(email) <= 200),
  display_name text not null check (char_length(display_name) between 2 and 80),
  headline text not null default '' check (char_length(headline) <= 90),
  bio text not null default '' check (char_length(bio) <= 1200),
  city text not null default '' check (char_length(city) <= 60),
  -- The mentor's own collection handle: the QR every buyer of their product scans.
  upi_id text not null check (upi_id ~ '^[A-Za-z0-9._-]{2,64}@[A-Za-z][A-Za-z0-9._-]{1,48}$'),
  payee_name text not null check (char_length(payee_name) between 2 and 50),
  expertise text[] not null default '{}',
  status text not null default 'pending' check (status in ('pending', 'approved', 'suspended')),
  review_note text not null default '' check (char_length(review_note) <= 400),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists mentors_status_idx on public.mentors (status, created_at desc);

alter table public.mentors enable row level security;

drop policy if exists "Mentors read their own and published profiles" on public.mentors;
drop policy if exists "Students open a mentor account" on public.mentors;
drop policy if exists "Mentors edit their own profile" on public.mentors;

-- Approved profiles are the shopfront; a mentor always reads their own, whatever
-- its status.
-- Published profiles are the shopfront, a mentor always reads their own, and the
-- platform mentors see every application so the review queue has rows to review.
create policy "Mentors read their own and published profiles"
  on public.mentors for select to anon, authenticated
  using (status = 'approved' or user_id = coalesce(auth.jwt() ->> 'sub', '') or public.is_workspace_mentor());

create policy "Students open a mentor account"
  on public.mentors for insert to authenticated
  with check (user_id = coalesce(auth.jwt() ->> 'sub', ''));

create policy "Mentors edit their own profile"
  on public.mentors for update to authenticated
  using (user_id = coalesce(auth.jwt() ->> 'sub', ''))
  with check (user_id = coalesce(auth.jwt() ->> 'sub', ''));

-- The owner fills in their profile; only Aditya's side ever moves an account
-- between pending, approved and suspended. A request with no JWT at all is a
-- server-side write (the CLI, a migration, the service key), so it is exempt.
create or replace function public.mentors_guard()
returns trigger
language plpgsql
as $fn$
declare
  v_role text := coalesce(auth.jwt() ->> 'role', '');
  v_sub text := coalesce(auth.jwt() ->> 'sub', '');
  v_reviewer boolean := public.is_workspace_mentor();
begin
  if v_role = '' or v_role = 'service_role' then
    new.updated_at := now();
    return new;
  end if;
  if v_role = 'anon' or v_sub = '' then
    raise exception 'Sign in before opening a mentor account' using errcode = '42501';
  end if;
  if new.user_id <> v_sub and not v_reviewer then
    raise exception 'A mentor account belongs to the signed-in user' using errcode = '42501';
  end if;
  if not v_reviewer then
    new.status := case when tg_op = 'UPDATE' then old.status else 'pending' end;
    new.review_note := case when tg_op = 'UPDATE' then old.review_note else '' end;
  end if;
  if new.status = 'approved' and (new.upi_id !~ '^[A-Za-z0-9._-]{2,64}@[A-Za-z][A-Za-z0-9._-]{1,48}$' or length(new.payee_name) < 2) then
    raise exception 'An approved mentor needs a valid UPI id and payee name' using errcode = '22023';
  end if;
  new.updated_at := now();
  return new;
end;
$fn$;

drop trigger if exists mentors_guard on public.mentors;
create trigger mentors_guard before insert or update on public.mentors
  for each row execute function public.mentors_guard();

-- ── What a mentor sells, at the price they choose ───────────────────────────
create table if not exists public.mentor_products (
  id bigint generated by default as identity primary key,
  mentor_user_id text not null references public.mentors (user_id) on delete cascade,
  slug text not null unique check (slug ~ '^[a-z0-9]+(-[a-z0-9]+){1,9}$'),
  kind text not null check (kind in ('service', 'digital')),
  title text not null check (char_length(title) between 3 and 90),
  summary text not null default '' check (char_length(summary) <= 240),
  details text not null default '' check (char_length(details) <= 4000),
  includes text[] not null default '{}',
  -- One-off, per session, monthly - the mentor words it, the price is fixed.
  format text not null default 'one-time' check (char_length(format) <= 60),
  -- The mentor decides. ₹10 to ₹25,000 keeps the band human and the ledger clean.
  price numeric(8, 2) not null check (price >= 10 and price <= 25000),
  -- Digital goods carry their own download link; services do not need one.
  file_url text not null default '' check (char_length(file_url) <= 500),
  -- A product may open the CodexSheet workspace as part of what it delivers.
  unlocks_workspace boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists mentor_products_mentor_idx on public.mentor_products (mentor_user_id, created_at desc);

alter table public.mentor_products enable row level security;

drop policy if exists "Published products are open to everyone" on public.mentor_products;
drop policy if exists "Mentors write their own products" on public.mentor_products;
drop policy if exists "Mentors edit their own products" on public.mentor_products;
drop policy if exists "Mentors retire their own products" on public.mentor_products;

-- A buyer sees an active product of an approved mentor; the owner also sees the
-- drafts they have not published.
create policy "Published products are open to everyone"
  on public.mentor_products for select to anon, authenticated
  using (
    mentor_user_id = coalesce(auth.jwt() ->> 'sub', '')
    or (
      active
      and exists (
        select 1 from public.mentors published
        where published.user_id = mentor_products.mentor_user_id
          and published.status = 'approved'
      )
    )
  );

create policy "Mentors write their own products"
  on public.mentor_products for insert to authenticated
  with check (mentor_user_id = coalesce(auth.jwt() ->> 'sub', ''));

create policy "Mentors edit their own products"
  on public.mentor_products for update to authenticated
  using (mentor_user_id = coalesce(auth.jwt() ->> 'sub', ''))
  with check (mentor_user_id = coalesce(auth.jwt() ->> 'sub', ''));

create policy "Mentors retire their own products"
  on public.mentor_products for delete to authenticated
  using (mentor_user_id = coalesce(auth.jwt() ->> 'sub', ''));

create or replace function public.mentor_products_guard()
returns trigger
language plpgsql
as $fn$
declare
  v_mentor public.mentors;
begin
  select * into v_mentor from public.mentors where user_id = new.mentor_user_id;
  if not found then
    raise exception 'Apply for a mentor account before publishing a product' using errcode = '42501';
  end if;
  if array_length(new.includes, 1) > 12 then
    raise exception 'Keep a product to 12 bullet points' using errcode = '22023';
  end if;
  new.updated_at := now();
  return new;
end;
$fn$;

drop trigger if exists mentor_products_guard on public.mentor_products;
create trigger mentor_products_guard before insert or update on public.mentor_products
  for each row execute function public.mentor_products_guard();

-- ── Claims against a mentor's own UPI statement ─────────────────────────────
create table if not exists public.market_orders (
  id bigint generated by default as identity primary key,
  reference text not null unique check (char_length(reference) between 6 and 40),
  product_id bigint not null references public.mentor_products (id) on delete restrict,
  -- Snapshots: a mentor who renames, reprices or retires a product must not
  -- rewrite the history of a student who already paid for it.
  mentor_user_id text not null,
  seller_name text not null default '',
  product_title text not null default '',
  amount numeric(8, 2) not null check (amount >= 10 and amount <= 25000),
  buyer_user_id text not null default '',
  buyer_email text not null default '' check (char_length(buyer_email) <= 200),
  buyer_name text not null check (char_length(buyer_name) between 1 and 120),
  buyer_contact text not null default '' check (char_length(buyer_contact) <= 160),
  upi_reference text not null default '' check (char_length(upi_reference) <= 80),
  note text not null default '' check (char_length(note) <= 1000),
  status text not null default 'awaiting'
    check (status in ('awaiting', 'confirmed', 'delivered', 'cancelled', 'refunded')),
  delivery_note text not null default '' check (char_length(delivery_note) <= 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists market_orders_seller_idx on public.market_orders (mentor_user_id, status, created_at desc);
create index if not exists market_orders_buyer_idx on public.market_orders (buyer_user_id, created_at desc);

alter table public.market_orders enable row level security;

drop policy if exists "Students buy from a mentor" on public.market_orders;
drop policy if exists "A buyer sees their own purchases" on public.market_orders;
drop policy if exists "A mentor updates their own sales" on public.market_orders;

-- Anyone may file a claim, signed in or not, exactly like the Family Pass.
create policy "Students buy from a mentor"
  on public.market_orders for insert to anon, authenticated
  with check (buyer_name <> '');

-- The seller's ledger and the buyer's receipts are the only readable views, and
-- both come straight from the row's own identity columns. An empty id never
-- matches: a guest paid without signing in can only ever read their own claim
-- through the reference code, exactly like the Family Pass.
create policy "A buyer sees their own purchases"
  on public.market_orders for select to anon, authenticated
  using (
    (coalesce(auth.jwt() ->> 'sub', '') <> '' and buyer_user_id = coalesce(auth.jwt() ->> 'sub', ''))
    or (
      coalesce(auth.jwt() ->> 'email', '') <> ''
      and buyer_email <> ''
      and lower(buyer_email) = lower(coalesce(auth.jwt() ->> 'email', ''))
    )
    or (
      coalesce(auth.jwt() ->> 'sub', '') <> ''
      and mentor_user_id = coalesce(auth.jwt() ->> 'sub', '')
    )
  );

create policy "A mentor updates their own sales"
  on public.market_orders for update to authenticated
  using (mentor_user_id = coalesce(auth.jwt() ->> 'sub', ''))
  with check (mentor_user_id = coalesce(auth.jwt() ->> 'sub', ''));

-- The price is never typed by the buyer: it is copied off the product at insert.
create or replace function public.market_orders_snapshot()
returns trigger
language plpgsql
as $fn$
declare
  v_product public.mentor_products;
  v_mentor public.mentors;
begin
  select * into v_product from public.mentor_products where id = new.product_id;
  if not found then
    raise exception 'That product no longer exists' using errcode = '23503';
  end if;
  select * into v_mentor from public.mentors where user_id = v_product.mentor_user_id;
  new.mentor_user_id := v_product.mentor_user_id;
  new.seller_name := coalesce(v_mentor.display_name, 'CodexSheet mentor');
  new.product_title := v_product.title;
  new.amount := v_product.price;
  new.updated_at := now();
  return new;
end;
$fn$;

drop trigger if exists market_orders_snapshot on public.market_orders;
create trigger market_orders_snapshot before insert on public.market_orders
  for each row execute function public.market_orders_snapshot();

