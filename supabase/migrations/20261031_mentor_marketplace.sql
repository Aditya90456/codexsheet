-- The mentor's own desk: who they are and what still sits in their queue.
create or replace function public.mentor_account()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $fn$
declare
  v_sub text := coalesce(auth.jwt() ->> 'sub', '');
  v_mentor public.mentors;
begin
  if v_sub = '' then
    return null;
  end if;
  select * into v_mentor from public.mentors where user_id = v_sub;
  if not found then
    return jsonb_build_object('status', 'none', 'platform_mentor', public.is_workspace_mentor());
  end if;
  return jsonb_build_object(
    'status', v_mentor.status,
    'profile', to_jsonb(v_mentor),
    'platform_mentor', public.is_workspace_mentor(),
    'open_sales', (
      select count(*) from public.market_orders placed
      where placed.mentor_user_id = v_sub and placed.status = 'awaiting'
    ),
    'earned', (
      select coalesce(sum(placed.amount), 0) from public.market_orders placed
      where placed.mentor_user_id = v_sub and placed.status in ('confirmed', 'delivered')
    )
  );
end;
$fn$;

revoke all on function public.mentor_account() from public;
grant execute on function public.mentor_account() to authenticated;

-- Aditya decides who gets a storefront.
create or replace function public.mentor_review_application(p_user_id text, p_status text, p_note text default '')
returns boolean
language plpgsql
security definer
set search_path = public
as $fn$
begin
  if not public.is_workspace_mentor() then
    raise exception 'Only CodexSheet platform mentors review applications' using errcode = '42501';
  end if;
  if p_status not in ('pending', 'approved', 'suspended') then
    raise exception 'Unknown mentor status' using errcode = '22023';
  end if;
  update public.mentors
    set status = p_status, review_note = coalesce(nullif(trim(p_note), ''), review_note), updated_at = now()
  where user_id = p_user_id;
  if not found then
    raise exception 'No mentor application for that user' using errcode = 'P0002';
  end if;
  -- A mentor who leaves also takes their shop window down.
  update public.mentor_products set active = false
  where mentor_user_id = p_user_id and p_status <> 'approved';
  return true;
end;
$fn$;

revoke all on function public.mentor_review_application(text, text, text) from public, anon;
grant execute on function public.mentor_review_application(text, text, text) to authenticated;

-- The seller ticks a reference against their own UPI statement.
create or replace function public.mentor_close_market_order(p_reference text, p_status text, p_note text default '')
returns boolean
language plpgsql
security definer
set search_path = public
as $fn$
begin
  if p_status not in ('confirmed', 'delivered', 'cancelled', 'refunded') then
    raise exception 'A sale moves to confirmed, delivered, cancelled or refunded' using errcode = '22023';
  end if;
  update public.market_orders placed
    set status = p_status,
        delivery_note = coalesce(nullif(trim(p_note), ''), placed.delivery_note),
        updated_at = now()
  where trim(lower(placed.reference)) = trim(lower(coalesce(p_reference, '')))
    and placed.mentor_user_id = coalesce(auth.jwt() ->> 'sub', '');
  if not found then
    raise exception 'That reference is not in your sales queue' using errcode = 'P0002';
  end if;
  return true;
end;
$fn$;

revoke all on function public.mentor_close_market_order(text, text, text) from public, anon;
grant execute on function public.mentor_close_market_order(text, text, text) to authenticated;

-- ── The workspace gate learns that mentoring is no longer one person ────────
-- A mentor's product can carry workspace access; a confirmed claim for one opens
-- the sheet the same way the Family Pass does.
create or replace function public.workspace_unlocked()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_workspace_mentor()
    or exists (
      select 1
      from public.mentorship_orders placed
      where placed.status in ('confirmed', 'delivered')
        and (
          (coalesce(auth.jwt() ->> 'sub', '') <> '' and placed.user_id = coalesce(auth.jwt() ->> 'sub', ''))
          or (coalesce(auth.jwt() ->> 'email', '') <> ''
              and placed.buyer_email <> ''
              and lower(placed.buyer_email) = lower(coalesce(auth.jwt() ->> 'email', '')))
        )
    )
    or exists (
      select 1
      from public.market_orders bought
      join public.mentor_products item on item.id = bought.product_id
      where bought.status in ('confirmed', 'delivered')
        and item.unlocks_workspace
        and (
          (coalesce(auth.jwt() ->> 'sub', '') <> '' and bought.buyer_user_id = coalesce(auth.jwt() ->> 'sub', ''))
          or (coalesce(auth.jwt() ->> 'email', '') <> ''
              and bought.buyer_email <> ''
              and lower(bought.buyer_email) = lower(coalesce(auth.jwt() ->> 'email', '')))
        )
    );
$$;

revoke all on function public.workspace_unlocked() from public;
grant execute on function public.workspace_unlocked() to anon, authenticated;

