-- Mentorship sessions get a real place on the platform: a private video room
-- the mentor starts from the roster, and a mentor <-> mentee chat lane bound
-- to the confirmed payment. Rooms reuse call_rooms/join_call_room; only the
-- mentee row records which room belongs to which student.

alter table public.mentees
  add column if not exists live_room_id uuid;

-- Sessions are real calls, so the mentor attaches a Google Meet link with them.
-- The platform room stays as the fallback for students who prefer it.
alter table public.mentees
  add column if not exists meeting_url text not null default '' check (char_length(meeting_url) <= 300);

-- A session is booked, not improvised: the mentor sets the call time.
alter table public.mentees
  add column if not exists scheduled_at timestamptz;

create table if not exists public.mentorship_messages (
  id bigint generated by default as identity primary key,
  mentee_id bigint not null references public.mentees(id) on delete cascade,
  sender_id text not null,
  content text not null check (char_length(content) between 1 and 4000),
  created_at timestamptz not null default now()
);

create index if not exists mentorship_messages_lane_idx
  on public.mentorship_messages (mentee_id, id desc);

alter table public.mentorship_messages enable row level security;

drop policy if exists "Mentor and mentee read their lane" on public.mentorship_messages;
drop policy if exists "Mentor and mentee post in their lane" on public.mentorship_messages;

-- Lanes follow the mentee row, so reassigning a record moves the history with
-- it. SECURITY DEFINER reads mentees past its own RLS.
create or replace function public.can_access_mentee_lane(p_mentee_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.mentees lane
    where lane.id = p_mentee_id
      and (
        lane.mentor_user_id = coalesce(auth.jwt() ->> 'sub', '')
        or lane.user_id = coalesce(auth.jwt() ->> 'sub', '')
      )
  );
$$;

revoke all on function public.can_access_mentee_lane(bigint) from public;
grant execute on function public.can_access_mentee_lane(bigint) to authenticated;

create policy "Mentor and mentee read their lane"
  on public.mentorship_messages for select to authenticated
  using (public.can_access_mentee_lane(mentee_id));

create policy "Mentor and mentee post in their lane"
  on public.mentorship_messages for insert to authenticated
  with check (
    public.can_access_mentee_lane(mentee_id)
    and sender_id = coalesce(auth.jwt() ->> 'sub', '')
  );

grant select, insert on public.mentorship_messages to authenticated;
grant usage, select on sequence public.mentorship_messages_id_seq to authenticated;

-- The lane streams, so the chat needs the table in the realtime publication.
do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'mentorship_messages'
  ) then
    alter publication supabase_realtime add table public.mentorship_messages;
  end if;
end;
$$;

-- Starting a session is a mentor action and stores the room on the mentee.
-- plpgsql cannot change a return type in place, so the old signatures drop first.
drop function if exists public.mentor_open_session(bigint);
drop function if exists public.mentor_open_session(bigint, text);

create function public.mentor_open_session(
  p_mentee_id bigint,
  p_meeting_url text default '',
  p_scheduled_at timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_room uuid;
  v_meet text := btrim(coalesce(p_meeting_url, ''));
begin
  if not public.is_workspace_mentor() then
    raise exception 'Only mentors can open a session' using errcode = '42501';
  end if;

  -- Only a real Google Meet link is stored; anything else would send a student
  -- somewhere the mentor did not intend.
  if v_meet <> '' and v_meet !~* '^https://meet\.google\.com/[a-z0-9/?=&%._-]+$' then
    raise exception 'Use a https://meet.google.com link or leave it empty for the platform room'
      using errcode = '22023', hint = v_meet;
  end if;

  v_room := gen_random_uuid();

  -- The room must exist in call_rooms or join_call_room rejects the student.
  insert into public.call_rooms (id, created_by)
  values (v_room, auth.jwt() ->> 'sub');

  -- A mentor only owns their own students; the room binds to that lane alone.
  update public.mentees lane
    set live_room_id = v_room,
        meeting_url = v_meet,
        scheduled_at = coalesce(p_scheduled_at, now() + interval '1 hour'),
        updated_at = now()
    where lane.id = p_mentee_id
      and lane.mentor_user_id = coalesce(auth.jwt() ->> 'sub', '');

  if not found then
    delete from public.call_rooms room where room.id = v_room;
    raise exception 'No such mentee' using errcode = 'P0002';
  end if;

  return jsonb_build_object(
    'room', v_room,
    'meeting_url', v_meet,
    'scheduled_at', coalesce(p_scheduled_at, now() + interval '1 hour')
  );
end;
$fn$;

revoke all on function public.mentor_open_session(bigint, text, timestamptz) from public;
grant execute on function public.mentor_open_session(bigint, text, timestamptz) to authenticated;

-- End (or start-over) closes the room for the student card.
create or replace function public.mentor_close_session(p_mentee_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_room uuid;
begin
  if not public.is_workspace_mentor() then
    raise exception 'Only mentors can close a session' using errcode = '42501';
  end if;

  update public.mentees lane
    set live_room_id = null, meeting_url = '', scheduled_at = null, updated_at = now()
    where lane.id = p_mentee_id
      and lane.mentor_user_id = coalesce(auth.jwt() ->> 'sub', '')
    returning lane.live_room_id into v_room;

  if v_room is not null then
    delete from public.call_rooms room where room.id = v_room;
  end if;
end;
$fn$;

revoke all on function public.mentor_close_session(bigint) from public;
grant execute on function public.mentor_close_session(bigint) to authenticated;
