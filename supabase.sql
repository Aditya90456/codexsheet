grant select (user_id, display_name) on public.profiles to authenticated;
grant insert on public.profiles to authenticated;
grant update (user_id, display_name) on public.profiles to authenticated;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (user_id, email, display_name)
  values (new.id::text, new.email, coalesce(new.raw_user_meta_data ->> 'display_name', ''))
  on conflict (user_id) do update
  set email = excluded.email,
      display_name = excluded.display_name,
      updated_at = now();
  return new;
end;
$$;

insert into public.profiles (user_id, email, display_name)
select id::text, email, coalesce(raw_user_meta_data ->> 'display_name', '')
from auth.users
on conflict (user_id) do update
set email = excluded.email,
    display_name = excluded.display_name,
    updated_at = now();

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

