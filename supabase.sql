-- Atomically claim the queued letters so two scheduler runs never send the same
-- offer letter twice.
create or replace function public.email_outbox_claim(p_limit integer default 6)
returns table (
  id bigint,
  to_address text,
  recipient_name text,
  subject text,
  body_html text,
  body_text text,
  kind text,
  ref text
)
language plpgsql
security definer
set search_path = public
as $fn$
declare
  v_limit integer := least(greatest(coalesce(p_limit, 6), 1), 20);
begin
  perform pg_advisory_xact_lock(hashtext('codexsheet-email-outbox'));

  return query
  with picked as (
    update public.email_outbox stamped
      set attempts = stamped.attempts + 1
    where stamped.id in (
      select pending.id
      from public.email_outbox pending
      where pending.status = 'queued'
      order by pending.queued_at
      limit v_limit
      for update of pending skip locked
    )
    returning stamped.id, stamped.to_address, stamped.recipient_name, stamped.subject,
      stamped.body_html, stamped.body_text, stamped.kind, stamped.ref
  )
  select picked.id, picked.to_address, picked.recipient_name, picked.subject,
    picked.body_html, picked.body_text, picked.kind, picked.ref
  from picked;
end;
$fn$;

