declare
  missing_problems integer;
begin
  select count(*)
  into missing_problems
  from generate_series(1, 250) as expected(problem_number)
  where not exists (
    select 1 from public.dsa_problem_content content
    where content.problem_number = expected.problem_number
  ) or not exists (
    select 1 from public.dsa_problem_test_cases test_case
    where test_case.problem_number = expected.problem_number
  );

  if missing_problems > 0 then
    raise exception 'Problem data setup is incomplete: % problem(s) are missing descriptions or test cases.', missing_problems;
  end if;
end;
$$;

