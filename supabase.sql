  id bigint generated by default as identity primary key,
  user_id text not null,
  title text not null default 'Untitled note',
  content text not null default '' check (char_length(content) <= 100000),
  updated_at timestamptz not null default now()
);

alter table public.personal_notes
  add column if not exists id bigint generated by default as identity;

alter table public.personal_notes
  add column if not exists title text not null default 'Untitled note';

do $$
declare
  primary_key_name text;
begin
  select conname into primary_key_name
  from pg_constraint
  where conrelid = 'public.personal_notes'::regclass
    and contype = 'p';

  if primary_key_name is not null and primary_key_name <> 'personal_notes_pkey' then
    execute format('alter table public.personal_notes drop constraint %I', primary_key_name);
  end if;
end;
$$;

alter table public.personal_notes
  drop constraint if exists personal_notes_pkey;

alter table public.personal_notes
  add constraint personal_notes_pkey primary key (id);

alter table public.personal_notes enable row level security;

drop policy if exists "Users manage their own personal notes" on public.personal_notes;
create policy "Users manage their own personal notes"
  on public.personal_notes for all
  using ((auth.jwt() ->> 'sub') = user_id)
  with check ((auth.jwt() ->> 'sub') = user_id);

grant select, insert, update on public.personal_notes to authenticated;
grant usage, select on sequence public.personal_notes_id_seq to authenticated;

create or replace function public.create_personal_notes_for_profile()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.personal_notes (user_id)
  select new.user_id
  where not exists (
    select 1 from public.personal_notes where user_id = new.user_id
  );
  return new;
end;
$$;

drop trigger if exists create_personal_notes_for_profile on public.profiles;
create trigger create_personal_notes_for_profile
  after insert on public.profiles
  for each row execute procedure public.create_personal_notes_for_profile();

insert into public.personal_notes (user_id)
select user_id
from public.profiles
where not exists (
  select 1
  from public.personal_notes existing_note
  where existing_note.user_id = profiles.user_id
);

