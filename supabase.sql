-- The seller's own queue now has to say what was bought, because a webinar is
-- worthless after its start time.
drop function if exists public.market_order_status(text);
create or replace function public.market_order_status(p_reference text)
returns table (
  reference text,
  product_title text,
  seller_name text,
  amount numeric,
  status text,
  delivered boolean,
  starts_at timestamptz,
  filed_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select placed.reference, placed.product_title, placed.seller_name, placed.amount, placed.status,
    placed.status in ('delivered', 'confirmed'), item.starts_at, placed.created_at
  from public.market_orders placed
  left join public.mentor_products item on item.id = placed.product_id
  where trim(lower(placed.reference)) = trim(lower(coalesce(p_reference, '')));
$$;

revoke all on function public.market_order_status(text) from public;
grant execute on function public.market_order_status(text) to anon, authenticated;

