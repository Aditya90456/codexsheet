export const hindiCourseTitles: Record<string, string> = Object.fromEntries(
  Object.entries(raw).map(([id, entry]) => [id, entry.title]),
);

/** Null when a lesson or step has no Hindi track, so the caller can speak the English line. */
export function hindiStep(lessonId: string, index: number): HindiStep | null {
  const step = raw[lessonId]?.steps[index];
  if (!step) return null;
  return { title: step[0], narration: step[1] };
}

export function hindiTitle(lessonId: string): string | null {
  return raw[lessonId]?.title ?? null;
}
