const failures = [];
let passed = 0;
function is(label, condition, detail = "") {
  if (condition) { passed += 1; console.log(`  ok   ${label}`); return; }
  failures.push(detail ? `${label} — ${detail}` : label);
  console.log(`  FAIL ${label}${detail ? ` — ${detail}` : ""}`);
}

function describe(error) {
  const hint = error?.hint ? ` (hint: ${error.hint})` : "";
  return `${String(error?.message ?? error)}${hint}`;
}
async function errorFrom(run) {
  try { await run(); return ""; } catch (error) { return describe(error); }
}
async function isRefused(label, run, phrase) {
  const message = await errorFrom(run);
  is(label, phrase ? message.toLowerCase().includes(phrase.toLowerCase()) : message !== "", message.slice(0, 130) || "the statement was allowed");
  return message;
}

async function oops(run) {
  try {
    return { value: await run(), problem: "" };
  } catch (error) {
    return { value: undefined, problem: describe(error) };
  }
}
// A call that is meant to work. Without this a single rejected statement ends
// the run with a stack trace instead of a line in the report.
async function works(label, run) {
  const outcome = await oops(run);
  is(label, outcome.value !== undefined, outcome.problem);
  return outcome.value;
}

