// (PGlite, the WASM build) with the tables it depends on, then behaves like two
// students and a stranger. This is the only way to try the network before the SQL
// is pasted into the live project, where a statement that fails halfway leaves
// everything after it unpasted.
//
//   npm i -D @electric-sql/pglite
//   node scripts/student-network-check.mjs
//
// The harness stands in for Supabase: anon/authenticated roles, auth.jwt(), the
// supabase_realtime publication, profiles, dsa_progress and the seeded sheet. The
// sheet rows and the XP arithmetic are the real ones, read out of the repo.
