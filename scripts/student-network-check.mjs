let acting = null;
async function signIn(sub) {
  acting = sub;
  await db.exec("reset role");
  await db.query("select set_config('app.claims', $1, false)", [sub ? JSON.stringify({ sub }) : "{}"]);
  await db.exec(sub ? "set role authenticated" : "set role anon");
}
// Some assertions need rows a student is deliberately not allowed to see. Look
  // at them as the owner, then hand the session back to who was signed in.
async function peek(sql, params = []) {
  await db.exec("reset role");
  const { rows } = await db.query(sql, params);
  await signIn(acting);
  return rows;
}
async function rpc(name, params = []) {
  const placeholders = params.map((_, index) => `$${index + 1}`).join(", ");
  const { rows } = await db.query(`select * from public.${name}(${placeholders})`, params);
  const keys = Object.keys(rows[0] ?? {});
  return rows.length === 1 && keys.length === 1 ? rows[0][keys[0]] : rows;
}

